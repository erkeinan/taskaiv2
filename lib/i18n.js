// Direction of a single piece of text, so Hebrew tasks read right-to-left
// even inside the English interface, and the other way around.
export function textDir(text) {
  const m = /[֐-׿؀-ۿ]|[A-Za-z]/.exec(text || '');
  if (!m) return 'auto';
  return /[A-Za-z]/.test(m[0]) ? 'ltr' : 'rtl';
}
